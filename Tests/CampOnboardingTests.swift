import Foundation

@main struct CampOnboardingTests {
    @MainActor static func main() async throws {
        let root = FileManager.default.temporaryDirectory.appendingPathComponent("camp-setup-" + UUID().uuidString)
        defer { try? FileManager.default.removeItem(at: root) }
        let setup = CampOnboarding(directory: root)
        precondition(setup.presented && setup.step == .profiles)
        precondition(CampOnboarding(directory: root).presented, "Quitting before the first click must preserve first-run setup")
        setup.back()
        precondition(setup.step == .profiles)
        setup.next()
        setup.pause()
        precondition(!setup.presented)
        let resumed = CampOnboarding(directory: root)
        precondition(!resumed.presented && resumed.step == .camp, "Deferred setup must not nag on launch")
        resumed.open()
        precondition(resumed.presented && resumed.step == .camp)
        resumed.finish()
        precondition(resumed.presented, "Only the last step completes setup")
        resumed.next(); resumed.back()
        precondition(resumed.step == .camp)
        resumed.next()
        precondition(resumed.step == .accounts && resumed.step.number == 3 && resumed.step.rawValue == 4,
                     "Cloud accounts fit between Camp and Project without changing saved step values")
        resumed.back()
        resumed.next(); resumed.next(); resumed.next()
        precondition(resumed.step == .ready)
        resumed.finish()
        let finished = CampOnboarding(directory: root)
        precondition(!finished.presented && finished.step == .ready)
        finished.open()
        precondition(finished.presented && finished.step == .profiles, "Completed setup can be revisited")
        let attrs = try FileManager.default.attributesOfItem(atPath: root.appendingPathComponent("setup.json").path)
        precondition(attrs[.posixPermissions] as? Int == 0o600)

        let existing = root.appendingPathComponent("existing")
        try FileManager.default.createDirectory(at: existing, withIntermediateDirectories: true)
        try Data("{}".utf8).write(to: existing.appendingPathComponent("session-index.json"))
        let upgrade = CampOnboarding(directory: existing)
        precondition(!upgrade.presented, "Upgrades must not interrupt existing users")
        upgrade.open()
        precondition(upgrade.presented && upgrade.step == .profiles)
        try Data("{bad json".utf8).write(to: existing.appendingPathComponent("setup.json"))
        let broken = CampOnboarding(directory: existing)
        precondition(!broken.presented && !broken.error.isEmpty)
        broken.open()
        precondition(broken.presented && broken.error.isEmpty, "Corrupt state must be recoverable")

        let integrated = root.appendingPathComponent("integrated")
        let store = CampStore(stateDirectory: integrated)
        precondition(store.onboarding.presented, "Detect first launch before the cache creates its directory")
        let known = CampSource(id: "known", provider: "Codex", root: "/fixture/.codex", label: "Known", count: 28)
        let found = CampSource(id: "found", provider: "Claude", root: "/fixture/.claude", label: "Found automatically", count: 0)
        store.sources = [known]
        store.applyProfileDiscovery([CampSource(id: known.id, provider: known.provider, root: known.root, label: known.label, count: 0), found, found])
        precondition(store.sources.count == 2 && store.sources.first(where: { $0.id == known.id })?.count == 28,
                     "Automatic discovery must preserve cached counts and deduplicate profiles")
        store.applyProfileDiscovery([])
        precondition(store.sources.count == 2, "A fast directory check cannot discard a prior source")
        for _ in 0..<300 where !store.projects.ready { try await Task.sleep(for: .milliseconds(10)) }
        precondition(store.projects.ready)
        let count = store.projects.projects.count
        let invalid = await store.onboarding.createProject(name: "", repositories: "", local: store.projects)
        precondition(invalid == nil && !store.onboarding.error.isEmpty && store.projects.projects.count == count)
        let unsafe = await store.onboarding.createProject(name: "Client", repositories: "https://token@github.com/owner/repo", local: store.projects)
        precondition(unsafe == nil && store.projects.projects.count == count)
        let id = await store.onboarding.createProject(name: "Client", repositories: "https://github.com/owner/repo", local: store.projects)
        precondition(id != nil && store.projects.byID[id!]?.name == "Client")
        precondition(store.projects.projects.count == count + 1 && store.onboarding.error.isEmpty)
        precondition(CampOnboarding(directory: integrated).projectID == id, "A created project remains selected after relaunch")
        precondition(store.sharing.shares.isEmpty && store.cloud.scope == nil && store.conversations.isEmpty,
                     "Setup must not share sessions, authenticate accounts, or start provider work")
        let json = try String(contentsOf: root.appendingPathComponent("setup.json"), encoding: .utf8)
        precondition(!json.contains("token") && !json.contains("email"))
        let unwritable = root.appendingPathComponent("not-a-directory")
        try Data("fixture".utf8).write(to: unwritable)
        let blocked = CampOnboarding(directory: unwritable)
        blocked.pause()
        precondition(!blocked.presented && !blocked.error.isEmpty, "A failed progress write must not trap the user in setup")
        print("PASS: setup first launch, upgrade, back/skip/resume, completion, private persistence and project validation")
    }
}
